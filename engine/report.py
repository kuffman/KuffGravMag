import os
from xml.sax.saxutils import escape
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from engine.forward import resolve_strike_mode
from engine.model_status import model_status_lines
from engine.project import project_sha256
import json


def generate_pdf_report(
    filename,
    figure_path,
    bodies,
    field_params,
    *,
    observations=None,
    survey_profile=None,
    processing_steps=None,
    project_name="Unsaved project",
):
    """
    Generates an executive geophysical modeling report PDF.
    """
    doc = SimpleDocTemplate(filename, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    story = []
    styles = getSampleStyleSheet()

    # Title & Subtitle
    title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], fontSize=22, leading=26, textColor=colors.HexColor("#1A365D"))
    subtitle_style = ParagraphStyle('SubStyle', parent=styles['Normal'], fontSize=11, leading=14, textColor=colors.HexColor("#4A5568"))

    story.append(Paragraph("KuffGravMag — Potential Field Modeling Report", title_style))
    story.append(Paragraph("Generated by KuffGravMag Geophysics Workbench", subtitle_style))
    story.append(Spacer(1, 15))

    for status in model_status_lines(bodies):
        story.append(Paragraph(status, subtitle_style))
    story.append(Paragraph(
        "Finite-prism magnetics assume uniform magnetization and no self-demagnetization. "
        "Total-field anomaly is the first-order projection onto the ambient field.",
        subtitle_style,
    ))
    story.append(Spacer(1, 12))

    # Regional Field Summary
    heading2 = ParagraphStyle('H2', parent=styles['Heading2'], fontSize=14, leading=18, textColor=colors.HexColor("#2B6CB0"))
    story.append(Paragraph("1. Regional Ambient Field Settings", heading2))
    story.append(Spacer(1, 6))

    field_data = [
        ["Parameter", "Value"],
        ["Earth Magnetic Field (F)", f"{field_params.get('F', 48000)} nT"],
        ["Field Inclination (I)", f"{field_params.get('Inc', 55)} deg"],
        ["Field Declination (D)", f"{field_params.get('Dec', 0)} deg"],
        ["Profile Azimuth (α)", f"{field_params.get('Alpha', field_params.get('alpha', 0))} deg"],
    ]
    t_field = Table(field_data, colWidths=[240, 240])
    t_field.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#EDF2F7")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.HexColor("#2D3748")),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E0")),
    ]))
    story.append(t_field)
    story.append(Spacer(1, 15))

    # Subsurface Bodies Table
    story.append(Paragraph("2. Subsurface Body Physical Properties", heading2))
    story.append(Spacer(1, 6))

    body_table_data = [["Body", "Density\nkg/m³", "χ SI", "Jr\nA/m",
                        "Remanent\nI / D deg", "Strike mode / Y bounds m"]]
    for b in bodies:
        mode = resolve_strike_mode(b.y_min, b.y_max, getattr(b, "strike_mode", None))
        body_table_data.append([
            b.name,
            f"{b.density:.1f}",
            f"{b.k_succ:.4f}",
            f"{b.J_r:.2f}",
            f"{b.I_r:.1f} / {b.D_r:.1f}",
            f"{mode}: [{b.y_min:g}, {b.y_max:g}]",
        ])

    t_bodies = Table(body_table_data, colWidths=[90, 58, 50, 50, 92, 160], repeatRows=1)
    t_bodies.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#2B6CB0")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('ALIGN', (1,0), (-1,-1), 'CENTER'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E0")),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor("#F7FAFC")]),
    ]))
    story.append(t_bodies)
    story.append(Spacer(1, 15))

    vertex_style = ParagraphStyle(
        "VertexDetail", parent=styles["BodyText"], fontSize=7.5, leading=9,
        textColor=colors.HexColor("#4A5568"),
    )
    for body in bodies:
        points = list(zip(body.x[:-1], body.z[:-1]))
        coordinate_text = "; ".join(f"({x:g}, {z:g})" for x, z in points)
        story.append(Paragraph(
            f"<b>{escape(str(body.name))} cross-section vertices x,z (m):</b> "
            f"{escape(coordinate_text)}",
            vertex_style,
        ))
        story.append(Spacer(1, 4))
    story.append(Spacer(1, 8))

    # Embedded Plot Figure
    story.append(Paragraph("3. Forward Model Anomaly Curves & Subsurface Geometry", heading2))
    story.append(Spacer(1, 8))
    if os.path.exists(figure_path):
        story.append(Image(figure_path, width=520, height=390))

    story.append(Spacer(1, 10))
    story.append(Paragraph("4. Project Provenance", heading2))
    project_hash = project_sha256(
        bodies,
        field_params,
        observations,
        survey_profile=survey_profile,
        processing_steps=processing_steps,
    )
    observation_count = 0
    if observations:
        values = observations.get("x")
        if values is not None:
            observation_count = len(values)
    survey_count = 0 if survey_profile is None else len(survey_profile.distance_m)
    provenance = [
        f"Project: {escape(str(project_name))}",
        f"Canonical input snapshot SHA-256: {project_hash}",
        f"Observed profile stations: {observation_count}",
        f"Versioned survey stations: {survey_count}",
        f"Recorded processing steps: {len(processing_steps or ())}",
    ]
    for line in provenance:
        story.append(Paragraph(line, subtitle_style))
    for step in processing_steps or ():
        step_json = json.dumps(step, sort_keys=True, ensure_ascii=False, allow_nan=False)
        story.append(Paragraph(escape(step_json), vertex_style))

    doc.build(story)
