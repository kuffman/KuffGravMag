import os
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_pdf_report(filename, figure_path, bodies, field_params):
    """
    Generates an executive geophysical modeling report PDF.
    """
    doc = SimpleDocTemplate(filename, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    story = []
    styles = getSampleStyleSheet()

    # Title & Subtitle
    title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], fontSize=22, leading=26, textColor=colors.HexColor("#1A365D"))
    subtitle_style = ParagraphStyle('SubStyle', parent=styles['Normal'], fontSize=11, leading=14, textColor=colors.HexColor("#4A5568"))

    story.append(Paragraph("KuffGravMag — 2.5D Potential Field Modeling Report", title_style))
    story.append(Paragraph("Generated by KuffGravMag Geophysics Workbench", subtitle_style))
    story.append(Spacer(1, 15))

    # Regional Field Summary
    heading2 = ParagraphStyle('H2', parent=styles['Heading2'], fontSize=14, leading=18, textColor=colors.HexColor("#2B6CB0"))
    story.append(Paragraph("1. Regional Ambient Field Settings", heading2))
    story.append(Spacer(1, 6))

    field_data = [
        ["Parameter", "Value"],
        ["Earth Magnetic Field (F)", f"{field_params.get('F', 48000)} nT"],
        ["Field Inclination (I)", f"{field_params.get('Inc', 55)} deg"],
        ["Profile Azimuth (α)", "0.0 deg (North-South)"],
    ]
    t_field = Table(field_data, colWidths=[240, 240])
    t_field.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#EDF2F7")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.HexColor("#2D3748")),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E0")),
    ]))
    story.append(t_field)
    story.append(Spacer(1, 15))

    # Subsurface Bodies Table
    story.append(Paragraph("2. Subsurface Body Physical Properties", heading2))
    story.append(Spacer(1, 6))

    body_table_data = [["Body Name", "Density (kg/m³)", "Susceptibility (SI)", "Remanence (A/m)", "Strike Y (m)"]]
    for b in bodies:
        body_table_data.append([
            b.name,
            f"{b.density:.1f}",
            f"{b.k_succ:.4f}",
            f"{b.J_r:.2f}",
            f"[{b.y_min:.0f}, {b.y_max:.0f}]"
        ])

    t_bodies = Table(body_table_data, colWidths=[130, 90, 90, 85, 85])
    t_bodies.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#2B6CB0")),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('ALIGN', (1,0), (-1,-1), 'CENTER'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E0")),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor("#F7FAFC")]),
    ]))
    story.append(t_bodies)
    story.append(Spacer(1, 15))

    # Embedded Plot Figure
    story.append(Paragraph("3. Forward Model Anomaly Curves & Subsurface Geometry", heading2))
    story.append(Spacer(1, 8))
    if os.path.exists(figure_path):
        story.append(Image(figure_path, width=520, height=390))

    doc.build(story)